export const fengshuiClassicChapters = fengshuiClassicBooks.flatMap((book) => book.chapters);

export function findFengshuiBook(slug: string) {
  return fengshuiClassicBooks.find((book) => book.slug === slug);
}

export function findFengshuiChapter(bookSlug: string, chapterSlug: string) {
  return fengshuiClassicChapters.find((chapter) => chapter.bookSlug === bookSlug && chapter.chapterSlug === chapterSlug);
}
